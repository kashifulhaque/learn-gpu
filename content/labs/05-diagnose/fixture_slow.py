import torch
from lab_common import load_cuda

CPP = """
torch::Tensor slow_scale(torch::Tensor x);
torch::Tensor slow_branchy(torch::Tensor x);
"""

CUDA = r"""
#include <torch/extension.h>
#include <c10/cuda/CUDAException.h>
#include <cuda_runtime.h>

// Kernel 1: out = 2 * x + 1 over a rows x cols row-major matrix.
// Thread tid maps to (row, col) with the row index changing fastest.
__global__ void slow_scale_kernel(const float* x, float* out, int rows, int cols) {
    int tid = blockIdx.x * blockDim.x + threadIdx.x;
    int n = rows * cols;
    if (tid >= n) return;
    int row = tid % rows;
    int col = tid / rows;
    int i = row * cols + col;
    out[i] = x[i] * 2.0f + 1.0f;
}

torch::Tensor slow_scale(torch::Tensor x) {
    TORCH_CHECK(x.is_cuda() && x.dim() == 2 && x.is_contiguous() && x.scalar_type() == torch::kFloat32,
                "x must be a contiguous 2-D float32 CUDA tensor");
    auto out = torch::empty_like(x);
    int rows = (int)x.size(0), cols = (int)x.size(1);
    int n = rows * cols;
    int threads = 256;
    int blocks = (n + threads - 1) / threads;
    slow_scale_kernel<<<blocks, threads>>>(x.data_ptr<float>(), out.data_ptr<float>(), rows, cols);
    C10_CUDA_KERNEL_LAUNCH_CHECK();
    return out;
}

// Kernel 3: even elements take one long arithmetic path, odd elements another.
__device__ __forceinline__ float path_a(float v) {
    for (int k = 0; k < 256; ++k) v = fmaf(v, 0.999f, 0.001f);
    return v;
}
__device__ __forceinline__ float path_b(float v) {
    for (int k = 0; k < 256; ++k) v = v * v * 0.5f + 0.25f;  // a different body, so nvcc cannot merge the two paths
    return v;
}

__global__ void slow_branchy_kernel(const float* x, float* out, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    if (i >= n) return;
    out[i] = (i & 1) ? path_b(x[i]) : path_a(x[i]);
}

torch::Tensor slow_branchy(torch::Tensor x) {
    TORCH_CHECK(x.is_cuda() && x.dim() == 1 && x.is_contiguous() && x.scalar_type() == torch::kFloat32,
                "x must be a contiguous 1-D float32 CUDA tensor");
    auto out = torch::empty_like(x);
    int n = (int)x.numel();
    int threads = 256;
    int blocks = (n + threads - 1) / threads;
    slow_branchy_kernel<<<blocks, threads>>>(x.data_ptr<float>(), out.data_ptr<float>(), n);
    C10_CUDA_KERNEL_LAUNCH_CHECK();
    return out;
}
"""


def _module():
    return load_cuda("diagnose_slow", CUDA, CPP, ["slow_scale", "slow_branchy"])


def slow_scale(x: torch.Tensor) -> torch.Tensor:
    """Kernel 1: 2 * x + 1 with neighboring threads a whole row apart."""
    return _module().slow_scale(x)


def slow_branchy(x: torch.Tensor) -> torch.Tensor:
    """Kernel 3: even and odd elements take different 256-step paths."""
    return _module().slow_branchy(x)


def slow_clip(tensors: list, thresh: float) -> list:
    """Function 2: scale each tensor so its largest absolute value is at most `thresh`.

    A tensor whose largest absolute value is already at most `thresh` comes back
    unchanged. The host reads each maximum back with `.item()` to decide.
    """
    out = []
    for t in tensors:
        m = t.abs().max().item()
        out.append(t * (thresh / m) if m > thresh else t.clone())
    return out
