"""A recorded-looking memory snapshot and an allocation trace for lab 40.

SYNTHESIZED. Nobody captured these on a GPU. They have the shape of the dict
that `torch.cuda.memory._snapshot()` returns (the PyTorch memory-snapshot
documentation lists the fields), trimmed to the fields the lab reads, and
every number is chosen so you can check it by hand. Do not edit this file.

Shape:

- `segments`: one dict per `cudaMalloc` segment, with `address`, `total_size`,
  `segment_type` ("small" or "large"), `allocated_size`, `active_size`, and
  `blocks`. A block has `address`, `size`, `requested_size`, `state`
  ("active_allocated", "active_awaiting_free", or "inactive"), and `frames`.
- `device_traces`: one list of trace entries per device. An entry has an
  `action` ("segment_alloc", "alloc", "free_requested", "free_completed",
  "oom"), `addr`, `size`, `stream`, and `frames`. An "oom" entry also has
  `device_free`. The first frame of a list is the innermost call.

Sizes are in bytes. `MiB` makes them readable.
"""

from __future__ import annotations

MiB = 1 << 20


def _frames(filename: str, line: int, name: str):
    return [{"filename": filename, "line": line, "name": name}]


def _block(addr, mib, state, frames=None):
    size = int(mib * MiB)
    return {
        "address": addr,
        "size": size,
        "requested_size": size,
        "state": state,
        "frames": frames or [],
    }


def _segment(addr, kind, blocks):
    total = sum(b["size"] for b in blocks)
    active = sum(b["size"] for b in blocks if b["state"] != "inactive")
    return {
        "address": addr,
        "total_size": total,
        "segment_type": kind,
        "stream": 0,
        "allocated_size": active,
        "active_size": active,
        "blocks": blocks,
    }


A, B, C = "active_allocated", "active_awaiting_free", "inactive"

BASE = 0x7F0000000000

# Four segments, 106 MiB reserved. 55 MiB is active and 51 MiB is inactive.
# The largest inactive block is 24 MiB, in the last segment.
SEGMENTS = [
    _segment(BASE, "small", [
        _block(BASE, 1, A, _frames("data.py", 10, "load_batch")),
        _block(BASE + 1 * MiB, 1, C),
    ]),
    _segment(BASE + 2 * MiB, "large", [
        _block(BASE + 2 * MiB, 6, A, _frames("model.py", 42, "embed")),
        _block(BASE + 8 * MiB, 4, C),
        _block(BASE + 12 * MiB, 4, A, _frames("model.py", 57, "attention")),
        _block(BASE + 16 * MiB, 6, C),
    ]),
    _segment(BASE + 22 * MiB, "large", [
        _block(BASE + 22 * MiB, 2, A, _frames("model.py", 61, "norm")),
        _block(BASE + 24 * MiB, 8, C),
        _block(BASE + 32 * MiB, 2, B, _frames("model.py", 70, "mlp")),
        _block(BASE + 34 * MiB, 8, C),
    ]),
    _segment(BASE + 42 * MiB, "large", [
        _block(BASE + 42 * MiB, 40, A, _frames("head.py", 88, "logits")),
        _block(BASE + 82 * MiB, 24, C),
    ]),
]


def _entry(action, addr, mib, frames=None, **extra):
    entry = {
        "action": action,
        "addr": addr,
        "size": int(mib * MiB),
        "stream": 0,
        "frames": frames or [],
    }
    entry.update(extra)
    return entry


# The history behind the segments. The running total of live bytes peaks at
# 79 MiB, when the 24 MiB log-softmax buffer from loss.py line 31 is live on
# top of the 55 MiB that the final state still holds.
TRACE = [
    _entry("segment_alloc", BASE, 2),
    _entry("alloc", BASE, 1, _frames("data.py", 10, "load_batch")),
    _entry("segment_alloc", BASE + 2 * MiB, 20),
    _entry("alloc", BASE + 2 * MiB, 6, _frames("model.py", 42, "embed")),
    _entry("alloc", BASE + 12 * MiB, 4, _frames("model.py", 57, "attention")),
    _entry("alloc", BASE + 106 * MiB, 8, _frames("model.py", 64, "gelu")),
    _entry("free_requested", BASE + 106 * MiB, 8),
    _entry("free_completed", BASE + 106 * MiB, 8),
    _entry("segment_alloc", BASE + 22 * MiB, 20),
    _entry("alloc", BASE + 22 * MiB, 2, _frames("model.py", 61, "norm")),
    _entry("alloc", BASE + 32 * MiB, 2, _frames("model.py", 70, "mlp")),
    _entry("segment_alloc", BASE + 42 * MiB, 64),
    _entry("alloc", BASE + 42 * MiB, 40, _frames("head.py", 88, "logits")),
    _entry("alloc", BASE + 82 * MiB, 24, _frames("loss.py", 31, "log_softmax")),
    _entry("free_requested", BASE + 82 * MiB, 24),
    _entry("free_completed", BASE + 82 * MiB, 24),
    _entry("oom", 0, 30, _frames("optim.py", 15, "step"), device_free=6 * MiB),
]

SNAPSHOT = {"segments": SEGMENTS, "device_traces": [TRACE]}

